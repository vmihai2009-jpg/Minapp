const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('bridge', {
  state: () => ipcRenderer.invoke('spotify:state'),
  cmd: (c, a) => ipcRenderer.invoke('spotify:cmd', c, a),
  size: (w, h, off) => ipcRenderer.send('win:size', w, h, off),
  artGet: (url) => ipcRenderer.invoke('art:get', url),
  dragStart: () => ipcRenderer.send('win:dragstart'),
  dragEnd: () => ipcRenderer.send('win:dragend'),
  capPrepare: (mode) => ipcRenderer.invoke('cap:prepare', mode),
  eqState: (s) => ipcRenderer.send('eq:state', s),
  prefsGet: () => ipcRenderer.invoke('prefs:get'),
  prefsSave: (u) => ipcRenderer.send('prefs:save', u),
  saveSkin: (name, buf) => ipcRenderer.invoke('skin:save', name, buf),
  log: (m) => ipcRenderer.send('app:log', m),
  capLost: (why) => ipcRenderer.send('cap:lost', why),
  eqMessage: (t) => ipcRenderer.send('eq:message', t),
  pinToggle: () => ipcRenderer.invoke('pin:toggle'),
  pinGet: () => ipcRenderer.invoke('pin:get'),
  onPin: (cb) => ipcRenderer.on('pin:state', (_e, v) => cb(v)),
  onDownload: (cb) => ipcRenderer.on('download:state', (_e, v) => cb(v)),
  onDownloadProgress: (cb) => ipcRenderer.on('download:progress', (_e, v) => cb(v)),
  downloadCtl: (a) => ipcRenderer.send('download:ctl', a),
  showMenu: () => ipcRenderer.send('menu:show'),
  onUpdate: (cb) => ipcRenderer.on('update:available', (_e, v) => cb(v)),
  updateGet: () => ipcRenderer.invoke('update:get'),
  updateInstall: () => ipcRenderer.send('update:install'),
  onWhatsNew: (cb) => ipcRenderer.on('whatsnew', (_e, v) => cb(v)),
  onWindowToggle: (cb) => ipcRenderer.on('window:toggle', (_e, id) => cb(id)),
  version: () => ipcRenderer.invoke('app:version'),
  openSkins: () => ipcRenderer.send('skins:open'),
  quit: () => ipcRenderer.send('app:quit'),
  lastSkin: () => ipcRenderer.invoke('skin:last'),
  onSkin: (cb) => ipcRenderer.on('skin:load', (_e, buf) => cb(buf)),
  vizBars: (b) => ipcRenderer.send('viz:bars', b),
  widgetGet: () => ipcRenderer.invoke('widget:get'),
  widgetSet: (m) => ipcRenderer.send('widget:set', m),
  onWidget: (cb) => ipcRenderer.on('widget:mode', (_e, m) => cb(m)),
  like: () => ipcRenderer.invoke('spotify:like'),
  spotLists: (force) => ipcRenderer.invoke('spotlists:get', force),
  spotPlayList: (uri) => ipcRenderer.invoke('spotlists:play', uri),
  spotConnect: () => ipcRenderer.send('spotlists:connect'),
  onMini: (cb) => ipcRenderer.on('mini:toggle', cb),
  albumState: (st) => ipcRenderer.send('album:state', st),
  onAlbumOptions: (cb) => ipcRenderer.on('album:options', (_e, o) => cb(o)),
  infoGet: (kind, song) => ipcRenderer.invoke('info:get', kind, song),
  infoPlay: (uri) => ipcRenderer.invoke('info:play', uri),
  infoState: (st) => ipcRenderer.send('info:state', st),
  onInfo: (cb) => ipcRenderer.on('info:options', (_e, o) => cb(o)),
  onSleep: (cb) => ipcRenderer.on('sleep:state', (_e, s) => cb(s)),
  sleepGet: () => ipcRenderer.invoke('sleep:get'),
  sleepNow: () => ipcRenderer.send('sleep:now'),
  listsAll: (force) => ipcRenderer.invoke('lists:all', force),
  listsPlay: (kind, id, name) => ipcRenderer.invoke('lists:play', kind, id, name),
  listsSearch: (key, q) => ipcRenderer.invoke('lists:search', key, q),
  listsFound: (r) => ipcRenderer.invoke('lists:found', r),
  onMilkdrop: (cb) => ipcRenderer.on('milkdrop:toggle', cb),
});
